/**
 * Turn a raw Axiom page capture into a committable DOM fixture.
 *
 * A raw `document.documentElement.outerHTML` from a logged-in session is not
 * safe to commit and not useful to keep whole. It carries the nav bar with the
 * wallet balance and portfolio value, a megabyte of Next.js hydration payload,
 * every stylesheet, and a base64 placeholder image inline on every card. None
 * of that is what the scraper reads.
 *
 * So this keeps the feed and throws away the rest. What survives is the Pulse
 * column sections and the ticker strip, with scripts, styles, SVG icons and
 * inline image data removed, wrapped in a minimal document.
 *
 * Run it on every new capture rather than editing one by hand:
 *   node scripts/scrub-dom-fixture.mjs <raw.html> <out.html>
 *
 * It refuses to write a file that still contains anything matching the
 * `--check` patterns, so a capture that holds a balance or a token fails loudly
 * instead of being committed quietly.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { JSDOM } from "jsdom";

const CARD_ATTR = "data-pulse-token-address";

/**
 * Patterns that must not survive into a committed fixture.
 *
 * Deliberately broad. A false positive costs one look; a false negative commits
 * a session artefact to a public repository.
 */
const FORBIDDEN = [
  { name: "JWT", re: /\beyJ[A-Za-z0-9_-]{10,}/ },
  { name: "bearer token", re: /\bBearer\s+[A-Za-z0-9._-]{10,}/i },
  { name: "api key", re: /\b(?:api[_-]?key|secret|privateKey)\b\s*[:=]/i },
  { name: "email address", re: /[\w.+-]+@[\w-]+\.[\w.]{2,}/ },
  { name: "next.js hydration payload", re: /self\.__next_f/ },
];

const [, , input, output] = process.argv;
if (!input || !output) {
  console.error("usage: node scripts/scrub-dom-fixture.mjs <raw.html> <out.html>");
  process.exit(2);
}

const dom = new JSDOM(readFileSync(input, "utf8"));
const doc = dom.window.document;

// --- Pick what to keep ------------------------------------------------------

// The column sections, identified by containing cards rather than by class, and
// the ticker strip, which is kept on purpose: it is full of `/meme/` anchors
// that are NOT pairs, and the scraper has to not pick them up.
const sections = [...doc.querySelectorAll("section")];
const kept = sections.filter(
  (section) =>
    section.querySelector(`[${CARD_ATTR}]`) !== null ||
    section.querySelector('a[href*="/meme/"]') !== null,
);

if (kept.length === 0) {
  console.error(`no Pulse sections found in ${input}; is this a Pulse capture?`);
  process.exit(1);
}

// --- Scrub ------------------------------------------------------------------

const out = new JSDOM(
  `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Axiom Pulse fixture</title></head><body></body></html>`,
);
const outDoc = out.window.document;
const root = outDoc.createElement("div");
root.setAttribute("data-fixture-root", "pulse");
outDoc.body.appendChild(root);

let removed = { scripts: 0, styles: 0, svg: 0, dataUris: 0 };

for (const section of kept) {
  const clone = outDoc.importNode(section, true);

  for (const el of [...clone.querySelectorAll("script,noscript,style,link,iframe")]) {
    if (el.tagName === "STYLE" || el.tagName === "LINK") removed.styles += 1;
    else removed.scripts += 1;
    el.remove();
  }

  // Icons. No text, no structure the scraper depends on, and a large share of
  // the byte count.
  for (const el of [...clone.querySelectorAll("svg")]) {
    removed.svg += 1;
    el.remove();
  }

  // Inline placeholder images: ~1.3KB of base64 on every card. Replaced with a
  // 1x1 GIF rather than deleted, so the fixture still exercises the scraper's
  // rule that a `data:` source is not hashable and must not be stored.
  for (const img of [...clone.querySelectorAll("img[src^='data:']")]) {
    removed.dataUris += 1;
    img.setAttribute("src", "data:image/gif;base64,R0lGODlhAQABAAAAACw=");
  }

  root.appendChild(clone);
}

const header = outDoc.createComment(
  ` Scrubbed Axiom Pulse capture. Generated by scripts/scrub-dom-fixture.mjs.\n` +
    `     Kept: the Pulse column sections and the ticker strip.\n` +
    `     Removed: scripts, styles, SVG icons, inline base64 images, and the\n` +
    `     surrounding chrome (nav, wallet balance, portfolio value).\n` +
    `     Do not hand-edit; re-run the scrubber on a fresh capture instead. `,
);
outDoc.body.insertBefore(header, root);

const html = out.serialize();

// --- Refuse to emit anything that still looks sensitive ---------------------

const hits = FORBIDDEN.filter((pattern) => pattern.re.test(html));
if (hits.length > 0) {
  console.error(
    `refusing to write ${output}; scrubbed output still matches: ` +
      hits.map((h) => h.name).join(", "),
  );
  process.exit(1);
}

writeFileSync(output, html);

const cards = root.querySelectorAll(`[${CARD_ATTR}]`).length;
const before = readFileSync(input, "utf8").length;
console.log(
  `${input} -> ${output}\n` +
    `  ${(before / 1024).toFixed(0)}KB -> ${(html.length / 1024).toFixed(0)}KB` +
    ` (${(100 - (html.length / before) * 100).toFixed(1)}% smaller)\n` +
    `  kept ${kept.length} sections, ${cards} cards\n` +
    `  removed ${removed.scripts} scripts, ${removed.styles} styles/links,` +
    ` ${removed.svg} svg, ${removed.dataUris} inline images`,
);
